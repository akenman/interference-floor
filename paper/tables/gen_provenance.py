# -*- coding: utf-8 -*-
"""从 number_provenance_check.json 生成 LaTeX provenance 附录表。

v3（Overleaf 编译反馈修复）：
  - 检查名里的 _ & % # 等 LaTeX 特殊字符自动转义（此前 ours_base 的 _ 触发
    "插入缺失的 $" 连锁错误）；
  - Unicode 字符（τ ĝ）替换为 ASCII/LaTeX 写法（pdfLaTeX 无 Unicode 支持）。
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
r = json.load(open(os.path.join(ROOT, 'analysis_output', 'number_provenance_check.json'),
                   encoding='utf-8'))

UNICODE_MAP = {'τ': '$\\tau$', 'ĝ': "$\\hat{g}$", '×': '$\\times$',
               '≤': '$\\le$', '≥': '$\\ge$', '−': '--'}


def esc(t):
    # 先替换 Unicode（在转义下划线之前，避免 $...$ 里的 _ 被二次处理）
    for k, v in UNICODE_MAP.items():
        t = t.replace(k, v)
    for ch in ('_', '&', '%', '#'):
        t = t.replace(ch, '\\' + ch)
    return t


def fmt(x):
    """数值走 :g；字符串型 claimed（如 'exactly [15, 4, 11]'）按文本转义后原样输出。"""
    return f"{x:g}" if isinstance(x, (int, float)) else esc(str(x))


rows = []
for c in r['checks']:
    ok = 'PASS' if c['ok'] else '\\textcolor{red}{FAIL}'
    rows.append(f"{esc(c['name'])} & {fmt(c['value'])} & {fmt(c['claimed'])} & {ok} \\\\")

tex = (
    "% AUTO-GENERATED by paper/tables/gen_provenance.py (v3, unicode-safe)\n"
    "% from analysis_output/number_provenance_check.json\n"
    f"% {len(r['checks'])} checks, generated from analysis_output/number_provenance_check.json\n"
    "{\\small\n"
    "\\begin{tabular}{p{8.2cm}rrc}\n"
    "\\toprule\n"
    "Check & computed & quoted & status \\\\\n"
    "\\midrule\n"
    + "\n".join(rows) + "\n"
    "\\bottomrule\n"
    "\\end{tabular}\n"
    "}\n"
)
out = os.path.join(ROOT, 'paper', 'latex', 'provenance.tex')
open(out, 'w', encoding='utf-8').write(tex)
print('provenance.tex regenerated (v3):', len(r['checks']), 'checks')
