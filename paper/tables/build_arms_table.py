# -*- coding: utf-8 -*-
"""生成 §6 臂清单表（评审 P1-7：五/六干预计数在四处互相冲突）。

用法：python paper/tables/build_arms_table.py
读：analysis_output/S1c_report.json, S1d_report.json, S1e_report.json, S1f_report.json
写：paper/latex/tab_arms.tex + analysis_output/arms_table.json

口径：
  - 单步/闭环数值 = 三 seed（42/43/44）均值，px；
  - FF = free-flight（contact-free）窗口，mixed = 含接触窗口；
  - 解码规则只作用于 rollout（k=3），故单步列留空；接触代价由 S1f 逐臂
    contact_rms(tau*)/unmasked 给出。
"""
import io
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
J = lambda p: json.load(io.open(os.path.join(ROOT, "analysis_output", p), encoding="utf-8"))
SEEDS = ("42", "43", "44")


def means(report, arm, field, sub=None):
    per = report[arm]
    vals = []
    for s in SEEDS:
        if s in per:
            v = per[s][field]
            vals.append(v[sub] if sub else v)
    return float(np.mean(vals)) if vals else float("nan")


HEADER = r"""% AUTO-GENERATED by paper/tables/build_arms_table.py
\begin{table}[t]
\centering
\caption{Every arm of \S\ref{sec:silence}, all on the exact-prior branch, three
seeds (means, px). \emph{FF} = contact-free windows; \emph{mixed} = windows
including contact; $k{=}3$ = closed-loop rollout on FF windows. Rows are grouped
by intervention family: five families, seven trained arms. The decode rule acts
at rollout time only, so it has no one-step column; its contact-regime cost is
@DMIN@--@DMAX@$\times$ the same arm ungated.}
\label{tab:arms}
\footnotesize
\begin{tabular}{@{}p{1.85cm}p{5.0cm}ccc@{}}
\toprule
Intervention family & Arm (prereg.) & FF one-step & mixed one-step & FF closed $k{=}3$ \\
\midrule
"""


def main():
    s1c = J("S1c_report.json")["results"]
    s1d = J("S1d_report.json")["results"]
    s1e = J("S1e_report.json")["results"]
    s1f = J("S1f_report.json")["results"]

    rows = [
        ("---", "baseline (unmodified exact-prior arm)", "",
         means(s1e, "baseline", "one_ff_clean"), means(s1e, "baseline", "one_mixed"),
         means(s1e, "baseline", "roll_ff_clean", "k=3")),
        ("loss reweighting", r"reweight $\times10$ on free-flight windows", "S1c",
         means(s1c, "wff10", "one_ff_clean"), means(s1c, "wff10", "one_mixed"),
         means(s1c, "wff10", "roll_ff_clean", "k=3")),
        ("dedicated pathway", "end-to-end gate between head and prior", "S1c",
         means(s1c, "gate", "one_ff_clean"), means(s1c, "gate", "one_mixed"),
         means(s1c, "gate", "roll_ff_clean", "k=3")),
        ("supervised gate", "gate trained on the contact flag (BCE)", "S1d",
         means(s1d, "sgate", "one_ff_clean"), means(s1d, "sgate", "one_mixed"),
         means(s1d, "sgate", "roll_ff_clean", "k=3")),
        ("loss-mass dose", r"closed-loop term $\times10$", "S1e",
         means(s1e, "W1", "one_ff_clean"), means(s1e, "W1", "one_mixed"),
         means(s1e, "W1", "roll_ff_clean", "k=3")),
        ("", r"both terms $\times10$", "S1e",
         means(s1e, "W2", "one_ff_clean"), means(s1e, "W2", "one_mixed"),
         means(s1e, "W2", "roll_ff_clean", "k=3")),
        ("", r"single-step term $\times100$", "S1e",
         means(s1e, "S", "one_ff_clean"), means(s1e, "S", "one_mixed"),
         means(s1e, "S", "roll_ff_clean", "k=3")),
    ]

    ff_closed, damage = [], []
    for arm in ("baseline", "F1", "F2"):
        for s in SEEDS:
            v = s1f[arm].get(s)
            if not v:
                continue
            ts = str(v["tau_star"])
            ff_closed.append(v["grid_B"][ts]["ff_rms"])
            damage.append(v["grid_B"][ts]["contact_rms"] / v["unmasked_B"]["contact_rms"])
    decode = dict(ff_closed_max=float(np.max(ff_closed)),
                  damage_min=float(np.min(damage)), damage_max=float(np.max(damage)),
                  n_points=len(ff_closed))

    best_one = min(r[3] for r in rows)
    best_closed = min(r[5] for r in rows)

    body = []
    for fam, name, prereg, one, mixed, closed in rows:
        one_s = r"\textbf{%.3f}" % one if one == best_one else "%.3f" % one
        cl_s = r"\textbf{%.3f}" % closed if closed == best_closed else "%.3f" % closed
        body.append("%s & %s%s & %s & %.3f & %s \\\\" % (
            fam, name, (" (%s)" % prereg) if prereg else "", one_s, mixed, cl_s))
    body.append(r"\midrule")
    body.append(r"decode rule & hard gate at $\tau^\ast$ (S1f) & --- & --- & "
                r"$%.1f{\times}10^{-4}$ \\" % (decode["ff_closed_max"] * 1e4))

    tex = (HEADER.replace("@DMIN@", "%.3f" % decode["damage_min"])
                 .replace("@DMAX@", "%.3f" % decode["damage_max"])
           + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    out_tex = os.path.join(ROOT, "paper", "latex", "tab_arms.tex")
    io.open(out_tex, "w", encoding="utf-8", newline="").write(tex)
    out_json = os.path.join(ROOT, "analysis_output", "arms_table.json")
    with io.open(out_json, "w", encoding="utf-8") as fh:
        json.dump(dict(
            source=["S1c_report.json", "S1d_report.json", "S1e_report.json",
                    "S1f_report.json"],
            seeds=list(SEEDS), units="px", aggregation="mean over seeds",
            rows=[dict(family=r[0], arm=r[1], prereg=r[2], ff_one_step=r[3],
                       mixed_one_step=r[4], ff_closed_k3=r[5]) for r in rows],
            decode_rule=decode), fh, ensure_ascii=False, indent=1)
    print("[save]", out_tex)
    print("[save]", out_json)
    for r in rows:
        print("   %-18s %-42s %-5s ff_one=%.3f mixed=%.3f ff_k3=%.3f" % r)
    print("   decode rule: ff_closed_max=%.2e damage=%.3f-%.3f (n=%d)"
          % (decode["ff_closed_max"], decode["damage_min"], decode["damage_max"],
             decode["n_points"]))


if __name__ == "__main__":
    main()
