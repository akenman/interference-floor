def main():
    e0 = J("E0_report.json")["arms"]
    base = {r["seed"]: r["one_step_model"] for r in e0["ours_base"]}
    gua = {r["seed"]: r["one_step_model"] for r in e0["ours_gua"]}
    base5 = {r["seed"]: r["rollout"]["k=5"] for r in e0["ours_base"]}
    gua5 = {r["seed"]: r["rollout"]["k=5"] for r in e0["ours_gua"]}
    g1_one, g1_k5 = paired(gua, base), paired(gua5, base5)

    sb = J("E1a_stageB_report.json")["summary"]
    meta = J("gate_paired_meta.json")
    fid = J("gate_fidelity.json")
    PAIRS = [("V1", "V1_nogua", 4, 3), ("V2a", "V2a_nogua", 16, 3),
             ("V2b", "V2b_nogua", 16, 3), ("V2c", "V2c_nogua", 16, 3),
             ("V3", "V3_nogua", 64, 3), ("V4", "V4_nogua", 256, 3)]
    g2 = []
    for v, nv, n_gua, axes in PAIRS:
        p = paired(sb[v]["seeds"], sb[nv]["seeds"])
        p.update(variant=v, control=nv, n_experts=n_gua,
                 occupied=occupied(fid, v, n_gua, axes),
                 collapse_gated=sb[v]["n_collapse"], collapse_control=sb[nv]["n_collapse"])
        g2.append(p)
    pfree = paired(sb["Vfree"]["seeds"], sb["V3_nogua"]["seeds"])
    pfree.update(variant="Vfree", control="V3_nogua", n_experts=64,
                 occupied=occupied(fid, "Vfree", 64, 3))

    # W8：容量混杂——门控臂用专家头替换了直接 state_head，参数量与对照不等。
    # 数值从 checkpoints_manifest.json 现算（评审的 -3.9% 由预注册附带，这里自算）。
    mf = J("checkpoints_manifest.json")["checkpoints"]
    E1 = "checkpoints-e1a-corrected"
    cap = dict(
        gen1={"ours_gua": cap_row(mf, "checkpoints-E0", "ours_gua", "ours_base", False)},
        gen2={v: cap_row(mf, E1, v, v, True) for v in
              ("V1", "V2a", "V2b", "V2c", "V3", "V4")},
        gen3={v: cap_row(mf, E1, v, "V3", False) for v in
              ("A1x64", "A2x64", "A3g1")},
        source="analysis_output/checkpoints_manifest.json",
        note="参数为清单中的 n_params（每臂所有 seed 须一致，cap_row 断言）；"
             "dev_pct = 门控臂/对照臂 - 1，负数表示门控臂参数更少",
    )
    cap["gen2"]["Vfree"] = cap_row(mf, E1, "Vfree", "V3", True)
    abl_fewer = [abs(cap["gen2"][v]["dev_pct"]) for v in
                 ("V1", "V2a", "V2b", "V2c", "V3", "Vfree")]
    cap["summary"] = dict(
        main_dev_pct=cap["gen1"]["ours_gua"]["dev_pct"],
        ablation_fewer_abs_range_pct=[min(abl_fewer), max(abl_fewer)],
        v4_dev_pct=cap["gen2"]["V4"]["dev_pct"],
        decoupled_max_abs_dev_pct=max(abs(x["dev_pct"]) for x in cap["gen3"].values()),
    )

    sd = J("E1a_stageD_report.json")["criteria_decoupled_exploratory"]
    g3 = []
    for k in sorted(sd):
        c = sd[k]
        g3.append(dict(criterion=k, variant=c["variant"], control=c["base"],
                       delta=c["delta"], ci_low=c["ci95"][0], ci_high=c["ci95"][1],
                       n=c["n_paired"], threshold=c["threshold"], verdict=c["verdict"],
                       occupied=occupied(fid, c["variant"], 64,
                                         1 if c["variant"] in ("A1x64", "A3g1") else 2)))

    def cell(p):
        return "%+.3f" % p["delta"], "[%+.3f, %+.3f]" % (p["ci_low"], p["ci_high"]), str(p["n"])

    def occ(o):
        if not o:
            return "---"
        return ("%d--%d of %d" % (o["lo"], o["hi"], o["n_experts"])) if o["lo"] != o["hi"] \
            else ("%d of %d" % (o["lo"], o["n_experts"]))

    L = []
    d, ci, n = cell(g1_one)
    L.append(r"main table & \texttt{ours\_gua} $-$ \texttt{ours\_base}, one-step & %s & %s & %s & --- \\" % (d, ci, n))
    d, ci, n = cell(g1_k5)
    L.append(r" & \quad closed-loop $k{=}5$ & %s & %s & %s & --- \\" % (d, ci, n))
    L.append(r"\midrule")
    for i, p in enumerate(g2):
        d, ci, n = cell(p)
        fam = (r"ten-seed ablation ($\Delta$ = gated $-$ ungated)"
               if i == 0 else "")
        L.append(r"%s & %s (%d experts) & %s & %s & %s & %s \\" % (
            fam, p["variant"], p["n_experts"], d, ci, n, occ(p["occupied"])))
    d, ci, n = cell(pfree)
    L.append(r" & Vfree (unstructured gate, 64 experts) & %s & %s & %s & --- \\" % (d, ci, n))
    L.append(r" & \quad fixed-effect combination over the seven variants & %+.3f & [%+.3f, %+.3f] & 7 & --- \\"
             % (meta["pooled"], meta["ci_low"], meta["ci_high"]))
    L.append(r"\midrule")
    LABEL = {"A1x64": "A1x64: supervise 1 axis, gate reads 1",
             "A2x64": "A2x64: supervise 2 axes, gate reads 2",
             "A3g1": "A3g1: supervise 3 axes, gate reads 1"}
    for i, c in enumerate(g3):
        fam = (r"capacity-decoupled ($\Delta$ = arm $-$ V3)" if i == 0 else "")
        d, ci, n = cell(c)
        L.append(r"%s & %s & %s & %s & %s & %s \\" % (
            fam, LABEL.get(c["variant"], c["variant"]), d, ci, n, occ(c["occupied"])))

    # 相位标签占用：论文 §5.2 的"专家占用审计"数字其实来自这里；顺带核对
    # "所有臂（含无门控臂）取值完全相同"这一断言
    hists = {}
    for arm, runs in e0.items():
        if runs and isinstance(runs[0], dict) and "gua_occupancy" in runs[0]:
            hists[arm] = tuple(round(float(v), 6) for v in runs[0]["gua_occupancy"].values())
    same_hists = len(set(hists.values())) == 1
    h = list(next(iter(hists.values())))
    top3 = sum(sorted(h, reverse=True)[:3])
    n_zero = sum(1 for x in h if x == 0.0)

    n_ci_excl = sum(1 for p in g2 if p["ci_low"] > 0)
    ssum = cap["summary"]
    tex = HEADER.replace("@TOP3@", "%.0f" % (top3 * 100)) \
                .replace("@NZERO@", "two" if n_zero == 2 else str(n_zero)) \
                .replace("@NARMS@", str(len(hists))) \
                .replace("@NCIEXCL@", str(n_ci_excl)) \
                .replace("@CAPMAIN@", "%.1f" % abs(ssum["main_dev_pct"])) \
                .replace("@CAPABLLO@", "%.0f" % ssum["ablation_fewer_abs_range_pct"][0]) \
                .replace("@CAPABLHI@", "%.0f" % ssum["ablation_fewer_abs_range_pct"][1]) \
                .replace("@CAPV4@", "%.0f" % abs(ssum["v4_dev_pct"])) \
                .replace("@CAPDEC@", "%.1f" % ssum["decoupled_max_abs_dev_pct"]) \
        + "\n".join(L) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    io.open(os.path.join(ROOT, "paper", "latex", "tab_c3_gating.tex"), "w",
            encoding="utf-8", newline="").write(tex)
    with io.open(os.path.join(ROOT, "analysis_output", "c3_gating_table.json"), "w",
                 encoding="utf-8") as fh:
        json.dump(dict(
            source=["E0_report.json", "E1a_stageB_report.json", "E1a_stageD_report.json",
                    "gate_paired_meta.json", "gate_fidelity.json", "S0b_report.json"],
            units="px", sign="positive = symbolic structure worse",
            generation1=dict(one_step=g1_one, closed_loop_k5=g1_k5,
                            means=dict(ours_base_one=float(np.mean(list(base.values()))),
                                       ours_gua_one=float(np.mean(list(gua.values())))),
                            note="E0 unified main table, 3 seeds, per-seed paired"),
            generation2=dict(variants=g2, vfree=pfree, meta=meta,
                             n_individual_ci_excl_zero=n_ci_excl),
            generation3=dict(block=g3,
                             note="paired against the coupled gated arm V3; no paired "
                                  "ungated counterpart is stored"),
            capacity=cap,
            occupancy_caveat="phase-label histogram identical across all arms including "
                             "ungated ones (data property, not gate routing)",
            phase_label_histogram=dict(top3_share=float(top3), n_empty_classes=n_zero,
                                       identical_across_arms=bool(same_hists),
                                       n_arms_checked=len(hists), histogram=h),
        ), fh, ensure_ascii=False, indent=1)
    print("[save] paper/latex/tab_c3_gating.tex")
    print("[save] analysis_output/c3_gating_table.json")
    print("gen1 one-step  ", g1_one)
    print("gen1 k5        ", g1_k5)
    for p in g2 + [pfree]:
        print("gen2 %-6s %+.3f [%+.3f, %+.3f] n=%d occ=%s" % (
            p["variant"], p["delta"], p["ci_low"], p["ci_high"], p["n"], occ(p["occupied"])))
    print("meta           %+.3f [%+.3f, %+.3f]" % (meta["pooled"], meta["ci_low"], meta["ci_high"]))
    for c in g3:
        print("gen3 %-7s %+.3f [%+.3f, %+.3f] n=%d %s" % (
            c["variant"], c["delta"], c["ci_low"], c["ci_high"], c["n"], occ(c["occupied"])))


if __name__ == "__main__":
    main()
