"""生成 C3（符号结构减分）的四代实验证据表（评审 P1-4：正文只有一句话概括，
附录只有一个名单，审稿人无法核验"四代一致"）。

用法：python paper/tables/build_c3_table.py
读：analysis_output/E0_report.json, E1a_stageB_report.json, E1a_stageD_report.json,
    gate_paired_meta.json, gate_fidelity.json, S0b_report.json
写：paper/latex/tab_c3_gating.tex + analysis_output/c3_gating_table.json

口径：
  - 所有配对差 = (门控臂 − 对照臂)，px，正数表示门控更差；
  - 第一代（主表）用 E0 的三 seed 逐 seed 配对；第二代（十 seed 消融）用 Stage B
    的 gua/nogua 逐 seed 配对；第三代（容量解耦）在存储分析里是**对 V3 配对**
    （不是对无门控臂），故该块明确标注对照臂，且不把无配对的均值读成优势；
  - "占用专家数"取 gate_fidelity.json 的 ngrp_gate 逐 run 极值。
"""
import ast
import io
import json
import os

import numpy as np
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
J = lambda p: json.load(io.open(os.path.join(ROOT, "analysis_output", p), encoding="utf-8"))


def paired(a_seeds, b_seeds, key=None):
    """逐 seed 配对差与 95% CI（t 分布）。"""
    common = sorted(set(a_seeds) & set(b_seeds), key=int)
    a = np.array([a_seeds[s] for s in common], dtype=float)
    b = np.array([b_seeds[s] for s in common], dtype=float)
    d = a - b
    n = len(d)
    se = d.std(ddof=1) / np.sqrt(n) if n > 1 else float("nan")
    half = stats.t.ppf(0.975, n - 1) * se if n > 1 else float("nan")
    return dict(delta=float(d.mean()), ci_low=float(d.mean() - half),
                ci_high=float(d.mean() + half), n=n, seeds=[int(s) for s in common])


def occupied(fid, variant, n_gua, axes):
    key = str((variant, n_gua, axes))
    runs = fid.get(key)
    if not runs:
        return None
    vals = [r.get("ngrp_gate") for r in runs if r.get("ngrp_gate") is not None]
    return dict(n_experts=n_gua, lo=int(min(vals)), hi=int(max(vals)), runs=len(vals)) if vals else None


def capacity(mf, root, name, nogua):
    """某臂在清单中的参数量集合（folder 前缀 name_s<seed>，nogua 由后缀区分）。"""
    vals = set()
    for c in mf:
        p = c["path"].replace("\\", "/")
        if not p.startswith(root + "/"):
            continue
        folder = p.split("/")[1]
        if not folder.startswith(name + "_s"):
            continue
        if ("_nogua" in folder) != nogua:
            continue
        vals.add(int(c["n_params"]))
    return sorted(vals)


def cap_row(mf, root, name, ctrl, ctrl_nogua, gated_nogua=False):
    g = capacity(mf, root, name, gated_nogua)
    c = capacity(mf, root, ctrl, ctrl_nogua)
    if len(g) != 1 or len(c) != 1:
        raise SystemExit(f"capacity(): {name}={g} ctrl={ctrl}={c} 不唯一，拒绝生成")
    dev = 100.0 * (g[0] / c[0] - 1.0)
    return dict(params=g[0], control=ctrl, control_params=c[0],
                dev_pct=round(dev, 2))


