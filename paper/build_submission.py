# -*- coding: utf-8 -*-
"""重建 TMLR 投稿包（评审 P0-5）。

用法：python paper/build_submission.py
输出：paper/TMLR_submission.zip

内容：稿件源文件 + 12 份预注册 + 守卫脚本与测试 + 全部存储 JSON 报告 + 说明。
不含：轨迹数据集（~320 MB）与检查点（体积原因，README 中已声明）。
"""
import glob
import json
import os
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, "TMLR_submission.zip")

README = """# Supplementary archive — "The Interference Floor: Why a Learned Corrector Degrades the Prior It Was Meant to Repair"

This archive accompanies the submission. Everything needed to trace a number in the
manuscript to its source is here, except the raw trajectory datasets and model
checkpoints (over 300 MB, excluded for size; see "Not included" below).

## Contents

| Path | What it is |
|---|---|
| `main.tex`, `provenance.tex`, `tab_arms.tex`, `tab_c3_gating.tex`, `tab_criteria.tex`, `tab_ladder_extension.tex`, `references.bib`, `tmlr.sty`, `tmlr.bst` | Manuscript sources (TMLR style); generated tables are `\\input` by `main.tex`. |
| `figs/` | Figures 1-8 as PDFs, generated by `generators/make_figures.py` and `generators/make_fig_floor.py` from the stored JSON reports (no hand-entered numbers). |
| `PREREG_CRITERIA_EN.md` | English summary of every criterion fixed by the twelve preregistrations, with thresholds quoted verbatim from them. |
| `preregistrations/` | The twelve preregistrations, written before the first run of each experiment. **Their prose is in Chinese**; the criteria, thresholds and calibration sources are structured JSON fields. |
| `generators/` | The scripts that produce the paper's figures, tables, provenance appendix and PDF from `analysis_output/`: {generators}. |
| `main.bbl` | The compiled bibliography, so the source builds without running BibTeX. |
| `guards/verify_numbers.py` | The number-provenance guard: each check is (source JSON, computed quantity, value quoted in the paper, tolerance). Current output: **{nchk}/{nchk} PASS**. |
| `guards/tests/` | The repository test suite ({ntests} files), covering prior-registry cross-implementation agreement, architecture wiring asserted from state dictionaries, checkpoint naming/overwrite protection, and ladder-extension provenance. |
| `guards/audit_citations.py` | Citation auditor: resolves titles/authors against arXiv and the publisher record. Current output: 17 entries, 0 discrepancies. |
| `guards/check_latex.py` | LaTeX structure guard: environment pairing, math-delimiter parity per line, `\\cite` keys against the bib in both directions, and `\\ref` targets against defined labels. Current output: PASS. |
| `provenance/number_provenance_check.json` | Machine-readable output of the provenance guard ({nchk} checks, all PASS); Appendix B of the paper is generated from this file. |
| `provenance/citation_audit.json` | Machine-readable output of the citation audit. |
| `analysis_output/*.json` | Every stored JSON report the manuscript draws on, including the ten-seed ladder comparison and the noise-floor matrix. |

## Reproducing the checks

From a checkout of the full repository (with `analysis_output/`, the datasets and the
checkpoint roots listed in the manifest):

```
python paper/tables/build_ladder_floor_r1.py # CPU-only; recomputes own-split ratios
python paper/tables/build_ladder_extension_table.py
python paper/verify_numbers.py                # {nchk}/{nchk} PASS
python -m pytest tests -q                     # current in the README
python paper/audit_citations.py               # needs network; 0 discrepancies
python paper/figures/make_figures.py          # regenerates figures from reports
python paper/tables/gen_provenance.py         # regenerates provenance.tex
```

## Not included

* `trajectories_v3.npz` (~285 MB) and `trajectories_hinge.npz` (~34 MB): the two
  world datasets. They are required by the training/evaluation pipeline and by checks
  that recompute window fractions, which therefore cannot be run from this archive alone.
* `checkpoints-*/`: trained model checkpoints. `analysis_output/checkpoints_manifest.json`
  lists them with 16-character SHA-256 digests.
"""


def main():
    entries = []

    def add(src, arcname):
        if not os.path.exists(src):
            raise SystemExit(f"missing: {src}")
        entries.append((src, arcname))

    latex = os.path.join(HERE, "latex")
    for name in ("main.tex", "provenance.tex", "tab_arms.tex", "tab_c3_gating.tex",
                 "tab_criteria.tex", "tab_ladder_extension.tex", "references.bib", "tmlr.sty", "tmlr.bst"): 
        add(os.path.join(latex, name), name)
    for f in sorted(glob.glob(os.path.join(latex, "figs", "*.pdf"))):
        add(f, "figs/" + os.path.basename(f))

    add(os.path.join(HERE, "PREREG_CRITERIA_EN.md"), "PREREG_CRITERIA_EN.md")
    # 内部评审存档**不进投稿包**（含"论文自相矛盾"等内部措辞）。
    # 投稿包只带面向审稿人的自述文档。
    for doc in ("README.md",):
        f = os.path.join(HERE, doc)
        if os.path.exists(f):
            add(f, "docs/" + doc)
    for fig in ("figures/fig7_floor_ceiling.pdf", "figures/fig7_floor_ceiling.png"):
        f = os.path.join(HERE, fig)
        if os.path.exists(f):
            add(f, "figures/" + os.path.basename(f))
    add(os.path.join(latex, "main.bbl"), "main.bbl")
    for f in sorted(glob.glob(os.path.join(HERE, "figures", "make_figures.py"))) + \
            sorted(glob.glob(os.path.join(HERE, "figures", "make_fig_floor.py"))) + \
            sorted(glob.glob(os.path.join(HERE, "tables", "*.py"))) + \
            [os.path.join(HERE, "build_pdf.py"),
             os.path.join(HERE, "repro_check.py"),
             os.path.join(HERE, "build_submission.py")]:
        add(f, "generators/" + os.path.basename(f))

    # 干扰地板的 post-hoc 分析：原始测量脚本 + 运行日志（可在分析产物上复跑）
    for pat in ("tmp_probe_replicate.py", "tmp_crosstalk_law*.py",
                "tmp_silence_ceiling.py", "tmp_silence_feasible.py",
                "tmp_trunk_isolation.py", "tmp_rollout_contrast.py",
                "tmp_ceiling_unified.py", "tmp_persist_unified_partial.py",
                "tmp_s1f_median_recheck.py", "tmp_s1f_finegrid.py",
                "tmp_s1f_allarms.py", "tmp_m5_observability_control.py",
                "tmp_m1_reproduction.py", "tmp_prereg_manifest.py"):
        for f in sorted(glob.glob(os.path.join(ROOT, pat))):
            add(f, "floor_analysis/" + os.path.basename(f))

    # 运行日志：只带"最终有效"的那几份。E5 的中间版本日志（tmp_e5_cal/fixed/hinge/log）
    # 记录的是我自己的口径 bug（假 +56% 增益），不进投稿包——它们留在 internal/ 内部留档。
    for log in ("tmp_crosstalk_log.txt", "tmp_law3_log.txt", "tmp_law4_log.txt",
                "tmp_replicate_log.txt", "tmp_ceiling_log.txt", "tmp_feasible_log.txt",
                "tmp_isolation_log.txt", "tmp_rollout_log.txt", "tmp_unified_log.txt",
                "tmp_e5_final_log.txt", "tmp_gate_log.txt", "tmp_ablation_log.txt"):
        f = os.path.join(ROOT, log)
        if os.path.exists(f):
            add(f, "floor_analysis/" + log)

    for extra in ("crosstalk_law.json", "crosstalk_law3.json", "crosstalk_law4.json",
                  "crosstalk_diag.json", "probe_replicate.json",
                  "silence_ceiling.json", "silence_feasible.json",
                  "trunk_isolation.json", "rollout_contrast.json",
                  "ceiling_unified_partial.json",
                  "ceiling_unified_120k.json"):
        f = os.path.join(ROOT, "analysis_output", extra)
        if os.path.exists(f):
            add(f, "floor_analysis/" + extra)

    for f in sorted(glob.glob(os.path.join(ROOT, "experiments", "prereg_*.json"))):
        add(f, "preregistrations/" + os.path.basename(f))
    for f in (os.path.join(HERE, "verify_numbers.py"),
              os.path.join(HERE, "audit_citations.py"),
              os.path.join(HERE, "check_latex.py")):
        add(f, "guards/" + os.path.basename(f))
    for f in sorted(glob.glob(os.path.join(ROOT, "tests", "*.py"))):
        add(f, "guards/tests/" + os.path.basename(f))
    for f in (os.path.join(ROOT, "analysis_output", "number_provenance_check.json"),
              os.path.join(ROOT, "analysis_output", "citation_audit.json")):
        add(f, "provenance/" + os.path.basename(f))
    for f in sorted(glob.glob(os.path.join(ROOT, "analysis_output", "*.json"))):
        if os.path.basename(f).startswith("_"):     # 临时中间产物不入包
            continue
        add(f, "analysis_output/" + os.path.basename(f))

    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        with open(os.path.join(ROOT, "analysis_output",
                               "number_provenance_check.json"), encoding="utf-8") as fh:
            prov = json.load(fh)
        nchk = len(prov["checks"])
        if not all(c.get("ok") for c in prov["checks"]):
            raise SystemExit("[拒发] number_provenance_check.json 存在未通过项")
        ntests = len(glob.glob(os.path.join(ROOT, "tests", "*.py")))
        generators = ", ".join(sorted({os.path.basename(a) for _, a in entries
                                       if a.startswith("generators/")}))
        readme = README.format(nchk=nchk, ntests=ntests, generators=generators)
        z.writestr("SUPPLEMENT_README.md", readme)
        for src, arcname in entries:
            z.write(src, arcname)

    size = os.path.getsize(OUT)
    print(f"[save] {OUT}  ({size/1024:.0f} KiB, {len(entries)+1} entries)")
    with zipfile.ZipFile(OUT) as z:
        for n in z.namelist():
            print("   ", n)


if __name__ == "__main__":
    main()
